// Gate Y — the section-to-part mapping gate (Y for "which part is it in?").
//
// WHY THIS EXISTS. Every check in this repository watched the part COUNT. The count is not the
// contract. `tools/paper-to-text.mjs` packs sections greedily against a 55,000-byte budget at
// section boundaries, so which part a section lands in depends on every byte before it. Measured on
// 29 July 2026: part 4 sat 173 bytes under budget, and adding 465 bytes to §6 moved §8 *Limitations
// and Honest Disclosures* out of part 4 and into part 5 **while the count stayed at seven**. Gate X
// prints the mapping and the tightest headroom on every run so a move is visible in a diff, and it
// asserts the count — but nothing asserted the mapping, and `assets/whitepaper.parts.json` cannot:
// it is rewritten by the same run that moves the boundary, so it agrees with every move.
//
// This gate holds four independent records to each other:
//
//   1. what the text ACTUALLY packs into, recomputed from assets/whitepaper.md
//   2. gates/paper-mapping.json — committed by hand, regenerated by nothing
//   3. assets/whitepaper.parts.json — generated
//   4. every place the mapping is PUBLISHED in prose, byte for byte
//
// It found a live defect on its first run. `assets/landing.html` — the service's own front page —
// published a SIX-part index, described part 4 as carrying "related work" (that is §9, in part 5),
// and told a judge with two minutes to spare to read part 6 for the checkable artifacts, which are
// in part 7. It had been wrong on the live service for days. `tools/docs-consistency.mjs` has
// precisely the rule that catches it — "a document that enumerates parts must enumerate all of
// them" — and walks only `.md` files, so it never opened the file.
//
//   node --test gates/gateY-paper-mapping.mjs      (npm run gate:y)
//   node gates/gateY-revert.mjs                    (npm run gate:y-revert)
import test from 'node:test';
import assert from 'node:assert/strict';
import { assessPaperMapping, headroomVerdict, BUDGET, HEADROOM_WARN } from './paper-integrity.mjs';
import { readMappingInputs } from './paper-inputs.mjs';

const IN = readMappingInputs();
const R = assessPaperMapping(IN);
const only = (rule) => R.findings.filter((f) => f.rule === rule);
const report = (rule) => { for (const f of only(rule)) console.error(`    ${f.rule}: ${f.msg}`); return only(rule); };

test('★ the committed section-to-part mapping is what the text actually packs into', () => {
  R.computed.forEach((t, i) => console.log(`    part ${i + 1}  ${String(R.sizes[i]).padStart(5)} B  ${t}`));
  const bad = report('MAPPING');
  assert.equal(bad.length, 0, `${bad.length} part(s) no longer carry the sections gates/paper-mapping.json says they carry`);
});

test('★ the generated whitepaper.parts.json agrees with the committed mapping', () => {
  // parts.json cannot witness its own drift — it is rewritten by the run that moves the boundary.
  // Held against the committed file, it witnesses the OTHER half: a part set never regenerated.
  const bad = report('PARTS-JSON');
  assert.equal(bad.length, 0, `${bad.length} disagreement(s) between the generated record and the committed one`);
});

test('★ every whitepaper.part*.md is exactly what the splitter would write from the source', () => {
  const bad = report('ON-DISK');
  assert.equal(bad.length, 0, 'a part file was hand-edited, or the source moved without a regeneration');
});

test('★ the HTML source and the markdown edition list the same sections in the same order', () => {
  const bad = report('SOURCE');
  assert.equal(bad.length, 0, 'assets/whitepaper.md is not a current render of assets/whitepaper.html');
});

test('★ every published section-to-part mapping still says what the contract says', () => {
  console.log(`    ${R.checkedSites} publication site(s) checked`);
  for (const n of R.notes) console.log(`    note: ${n}`);
  const bad = report('PUBLISHED');
  assert.equal(bad.length, 0, `${bad.length} published mapping(s) disagree with gates/paper-mapping.json`);
});

test('★ the packing budget this gate computes against is still the generator\'s budget', () => {
  const bad = report('BUDGET');
  assert.equal(bad.length, 0, 'tools/paper-to-text.mjs changed its budget — every figure in this gate is against the wrong number');
});

test('★ headroom: no part over budget, and a warning well before one is', () => {
  const v = headroomVerdict(R.headroom);
  R.headroom.forEach((h, i) => console.log(`    part ${i + 1}  ${String(h).padStart(5)} B headroom of ${BUDGET} B`));
  console.log(`    ${v.message}`);
  if (v.warn) {
    console.log(`    WARNING — the hard assertion above fires only AFTER a boundary has moved and the`);
    console.log(`    published mapping is already wrong. This fires while the cheap remedy still exists.`);
  }
  // The warning is deliberately NOT an assertion. 173 B is a legitimate state of the document; it is
  // not a defect, it is a thin margin. Failing on it would demand rewriting correct prose to satisfy
  // a gate, which is how a gate gets switched off. The defect is the mapping moving, and that is
  // asserted above.
  assert.equal(v.over, false, v.message);
  assert.ok(R.headroom.length >= 2, 'fewer than two parts — the packing computed nothing');
});

test('★ the gate examined a non-trivial corpus (a checker that reads nothing passes every time)', () => {
  assert.ok(IN.contract.parts.length >= 2, 'the committed mapping is empty');
  assert.equal(IN.onDisk.length, IN.contract.parts.length, 'the number of part files on disk differs from the committed mapping');
  assert.ok(R.checkedSites >= (IN.contract.minimumSitesChecked ?? 2), `only ${R.checkedSites} publication sites were readable`);
  assert.ok(HEADROOM_WARN > 0);
  console.log(`    ${IN.contract.parts.length} parts, ${IN.onDisk.length} files on disk, ${R.checkedSites} publication sites, ${R.findings.length} findings`);
});
