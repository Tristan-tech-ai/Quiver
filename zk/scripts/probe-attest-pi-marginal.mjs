// What does ONE public input actually cost a Plonk verify, measured well enough to extrapolate?
//
// WHY THIS EXISTS. gateAT prices a set-exactness pairing check at 2N+2 public signals, which at the
// service's N=244 ceiling is 490 — far past anything this repository can build. So the whole gas leg
// rests on a marginal gas-per-public-signal and on the ERROR BAR of that marginal. Both were being
// estimated from an OLS through THREE points (liquidation 8, concentration 12, portfoliogate 28).
// Three points and two fitted parameters leave ONE residual degree of freedom, so the standard error of
// the slope is itself a wildly noisy quantity — and it gets multiplied by 3 x 490 = 1470 to form the
// worst-case bound. Measured consequence: over 8 independent gate runs the published headroom figure
// ("the worst honest case consumes X% of the central margin") ranged 21.0% to 36.5%, and a ninth run
// reached 46.9%. A figure that moves that much is not a figure.
//
// THE INSTRUMENT. Public-input handling in a Plonk verifier is a generic loop over nPublic — it
// evaluates the public-input polynomial and folds each signal in. It does not depend on what the
// circuit MEANS. So the marginal can be measured with a circuit whose only property of interest is how
// many public signals it has, exactly as padprobe.circom is a measuring stick for domain size. That
// makes the witness free to construct, so the number of points is a choice rather than a constraint.
//
// AND IT IS CROSS-CHECKED AGAINST REAL CIRCUITS. A synthetic instrument is worth nothing if it does not
// predict the real thing, so the fitted line is held against gateAT's own measured means for
// liquidation (8), concentration (12) and portfoliogate (28) — read from its artifact rather than
// re-measured here, so this probe cannot quietly re-derive them into agreement.
//
// Run: node zk/scripts/probe-attest-pi-marginal.mjs [samplesPerPoint]
import { readFileSync, writeFileSync, existsSync, rmSync, renameSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ZK = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const BUILD = path.join(ZK, 'build');
const CIRCUITS = path.join(ZK, 'circuits');
const PTAU = 'build/hez_final_12.ptau';
const CLI = path.join(ZK, 'node_modules', 'snarkjs', 'build', 'cli.cjs');
const SAMPLES = Number(process.argv[2] || 10);

// K public inputs + 1 public output. Chosen to span 2..64 signals, which is as wide as the ptau on hand
// allows while keeping every point a real measurement rather than an extrapolation.
const KS = [1, 3, 7, 11, 15, 19, 27, 35, 49, 63];

const sj = (await import('snarkjs')).default ?? (await import('snarkjs'));
const solc = (await import('solc')).default ?? (await import('solc'));
const { EVM } = await import('@ethereumjs/evm');
const { Common, Chain, Hardfork } = await import('@ethereumjs/common');
const { keccak256 } = await import('ethereum-cryptography/keccak.js');
const { utf8ToBytes, bytesToHex, hexToBytes } = await import('ethereum-cryptography/utils.js');

const caller = hexToBytes('1000000000000000000000000000000000000001');
async function freshCall(bytecode, calldata) {
  const evm = await EVM.create({ common: new Common({ chain: Chain.Mainnet, hardfork: Hardfork.Cancun }) });
  const dep = await evm.runCall({ caller: { bytes: caller }, data: hexToBytes(bytecode), gasLimit: 300_000_000n });
  if (dep.execResult.exceptionError) throw new Error(`deploy: ${dep.execResult.exceptionError}`);
  const res = await evm.runCall({ caller: { bytes: caller }, to: dep.createdAddress, data: calldata, gasLimit: 300_000_000n });
  if (res.execResult.exceptionError) throw new Error(`call: ${res.execResult.exceptionError}`);
  return { gas: Number(res.execResult.executionGasUsed), ret: bytesToHex(res.execResult.returnValue) };
}
// EIP-2028 intrinsic calldata gas, the same accounting gateAT uses on both sides of its comparison.
const cdGas = (b) => { let g = 0; for (const x of b) g += x === 0 ? 4 : 16; return g; };

const SRC = (K) => `pragma circom 2.1.6;

// NOT a Quiver statement. A measuring stick for the cost of a PUBLIC INPUT, generated by
// zk/scripts/probe-attest-pi-marginal.mjs. A chain of multiplications keeps every constraint
// quadratic so Plonk has real gates to prove, and all-ones is a satisfying witness.
template PubProbe(K) {
    signal input xs[K];
    signal output out;
    signal acc[K + 1];
    acc[0] <== xs[0];
    for (var i = 0; i < K; i++) {
        acc[i + 1] <== acc[i] * xs[i];
    }
    out <== acc[K];
}

component main {public [xs]} = PubProbe(${K});
`;

const generated = [];
function build(K) {
  const name = `pubprobe${K}`;
  const src = path.join(CIRCUITS, `${name}.circom`);
  writeFileSync(src, SRC(K));
  generated.push(src);
  const run = (cmd, args) => execFileSync(cmd, args, { cwd: ZK, stdio: ['ignore', 'pipe', 'pipe'], timeout: 900_000 });
  run(path.join(ZK, 'circom.exe'), [`circuits/${name}.circom`, '--r1cs', '--wasm', '--sym', '-o', 'build']);
  run(process.execPath, [CLI, 'plonk', 'setup', `build/${name}.r1cs`, PTAU, `build/${name}_plonk.zkey`]);
  run(process.execPath, [CLI, 'zkey', 'export', 'verificationkey', `build/${name}_plonk.zkey`, `build/${name}_vk.json`]);
  const solName = `Pubprobe${K}Verifier.sol`;
  run(process.execPath, [CLI, 'zkey', 'export', 'solidityverifier', `build/${name}_plonk.zkey`, `build/${solName}`]);
  const wc = path.join(BUILD, `${name}_js`, 'witness_calculator.js');
  if (existsSync(wc)) renameSync(wc, path.join(BUILD, `${name}_js`, 'witness_calculator.cjs'));
  return { name, solName };
}

console.log(`PROBE — what one public input costs a Plonk verify — ${new Date().toISOString()}`);
console.log(`  ${KS.length} signal counts, ${SAMPLES} real proofs each, fresh EVM per call\n`);

const pts = [];
for (const K of KS) {
  const { name, solName } = build(K);
  const compiled = JSON.parse(solc.compile(JSON.stringify({
    language: 'Solidity',
    sources: { [solName]: { content: readFileSync(path.join(BUILD, solName), 'utf8') } },
    settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: 'paris', outputSelection: { '*': { '*': ['evm.bytecode.object'] } } },
  })));
  const cerr = (compiled.errors || []).filter((e) => e.severity === 'error');
  if (cerr.length) throw new Error(cerr.map((e) => e.formattedMessage).join('\n'));
  const key = Object.keys(compiled.contracts[solName]).find((x) => /verifier/i.test(x) && !/^I[A-Z]/.test(x));
  const V = compiled.contracts[solName][key];

  const zkey = path.join(BUILD, `${name}_plonk.zkey`);
  const wasm = path.join(BUILD, `${name}_js`, `${name}.wasm`);
  const builder = await require(path.join(BUILD, `${name}_js`, 'witness_calculator.cjs'))(readFileSync(wasm));
  const vk = JSON.parse(readFileSync(path.join(BUILD, `${name}_vk.json`), 'utf8'));
  const witness = { xs: Array(K).fill('1') };

  const totals = []; let nSig = null;
  for (let i = 0; i < SAMPLES; i++) {
    const { proof, publicSignals } = await sj.plonk.prove(zkey, await builder.calculateWTNSBin(witness, 0));
    if (!(await sj.plonk.verify(vk, publicSignals, proof))) throw new Error(`${name} sample ${i} fails off chain`);
    const r = await sj.plonk.exportSolidityCallData(proof, publicSignals);
    const [pw, sw] = JSON.parse(`[${r.replace(/\]\s*\[/g, '],[')}]`);
    const sel = bytesToHex(keccak256(utf8ToBytes(`verifyProof(uint256[24],uint256[${sw.length}])`))).slice(0, 8);
    const cd = hexToBytes(sel + [...pw, ...sw].map((v) => BigInt(v).toString(16).padStart(64, '0')).join(''));
    const res = await freshCall(V.evm.bytecode.object, cd);
    if (!/1$/.test(res.ret)) throw new Error(`${name} sample ${i} fails ON CHAIN`);
    totals.push(res.gas + cdGas(cd)); nSig = sw.length;
  }
  if (nSig !== vk.nPublic) throw new Error(`${name}: calldata carried ${nSig} signals but the vk says nPublic=${vk.nPublic}`);
  const n = totals.length;
  const mean = totals.reduce((a, b) => a + b, 0) / n;
  const sd = Math.sqrt(totals.reduce((a, b) => a + (b - mean) ** 2, 0) / (n - 1));
  const se = sd / Math.sqrt(n);
  pts.push({ circuit: name, publicSignals: nSig, samples: n, mean: Number(mean.toFixed(1)), sd: Number(sd.toFixed(1)), se: Number(se.toFixed(1)) });
  console.log(`  ${String(nSig).padStart(3)} signals   mean ${String(Math.round(mean)).padStart(8)} gas   sd ${String(Math.round(sd)).padStart(6)}   SE ${String(se.toFixed(1)).padStart(7)}`);
}

// ---- OLS with a PROPER slope standard error (n-2 dof, not 1) ----------------------------------------
const n = pts.length;
const mx = pts.reduce((a, p) => a + p.publicSignals, 0) / n;
const my = pts.reduce((a, p) => a + p.mean, 0) / n;
const Sxx = pts.reduce((a, p) => a + (p.publicSignals - mx) ** 2, 0);
const slope = pts.reduce((a, p) => a + (p.publicSignals - mx) * (p.mean - my), 0) / Sxx;
const base = my - slope * mx;
const resid = pts.map((p) => ({ publicSignals: p.publicSignals, mean: p.mean, fitted: Number((base + slope * p.publicSignals).toFixed(1)), residual: Number((p.mean - (base + slope * p.publicSignals)).toFixed(1)) }));
const dof = n - 2;
const sigma2 = resid.reduce((a, r) => a + r.residual ** 2, 0) / dof;   // residual variance, n-2 dof
const seSlope = Math.sqrt(sigma2 / Sxx);
const seAtX = (x) => Math.sqrt(sigma2 * (1 / n + (x - mx) ** 2 / Sxx));  // SE of the fitted MEAN at x

console.log(`\n  OLS over ${n} points, ${dof} residual dof`);
console.log(`    marginal            ${slope.toFixed(2)} gas per public signal   (SE ${seSlope.toFixed(2)})`);
console.log(`    base at 0 signals   ${base.toFixed(0)} gas`);
console.log(`    worst |residual|    ${Math.max(...resid.map((r) => Math.abs(r.residual))).toFixed(0)} gas   (residual sd ${Math.sqrt(sigma2).toFixed(0)})`);
console.log(`    R^2                 ${(1 - resid.reduce((a, r) => a + r.residual ** 2, 0) / pts.reduce((a, p) => a + (p.mean - my) ** 2, 0)).toFixed(6)}`);

// ---- cross-check against gateAT's real circuits -----------------------------------------------------
const gatePath = path.join(BUILD, 'gateAT-attest-no-snark.json');
let crossCheck = null;
if (existsSync(gatePath)) {
  const g = JSON.parse(readFileSync(gatePath, 'utf8'));
  crossCheck = (g.onChain.linearityResiduals || []).map((r) => {
    const predicted = base + slope * r.publicSignals;
    return {
      circuit: r.circuit, publicSignals: r.publicSignals, realMeanGas: r.mean,
      predictedFromProbe: Number(predicted.toFixed(1)),
      deltaGas: Number((r.mean - predicted).toFixed(1)),
      deltaPct: Number(((r.mean - predicted) / r.mean * 100).toFixed(3)),
    };
  });
  console.log(`\n  cross-check against gateAT's REAL circuits (its artifact, not re-measured here):`);
  for (const c of crossCheck) console.log(`    ${c.circuit.padEnd(14)} ${String(c.publicSignals).padStart(2)} signals   real ${String(Math.round(c.realMeanGas)).padStart(7)}   probe predicts ${String(Math.round(c.predictedFromProbe)).padStart(7)}   delta ${String(Math.round(c.deltaGas)).padStart(6)} gas (${c.deltaPct}%)`);
}

// ---- the ceiling comparison, redone on the stable marginal -------------------------------------------
const NC = 244, SIG = 2 * NC + 2;
const DIRECT = 708175;   // deterministic, from gateAT's artifact-backed direct measurement
const central = base + slope * SIG;
const se3 = 3 * seAtX(SIG);
const worst = central - se3;
const marginCentral = central - DIRECT;
const marginWorst = worst - DIRECT;
const fraction = (marginCentral - marginWorst) / marginCentral;

console.log(`\n  at N=${NC} (${SIG} public signals):`);
console.log(`    pairing check central   ${Math.round(central)} gas   (3 SE of the fitted mean: +-${Math.round(se3)})`);
console.log(`    pairing check worst     ${Math.round(worst)} gas`);
console.log(`    direct check            ${DIRECT} gas`);
console.log(`    margin central/worst    ${Math.round(marginCentral)} / ${Math.round(marginWorst)} gas`);
console.log(`    worst case consumes     ${(fraction * 100).toFixed(1)}% of the central margin`);

// ---- N=64, where the gas leg is supposed to be decisive rather than close ---------------------------
const DIRECT64 = 190931;   // deterministic, from gateAT's artifact
const SIG64 = 2 * 64 + 2;
const pairing64 = base + slope * SIG64;
console.log(`\n  at N=64 (${SIG64} public signals): direct ${DIRECT64} vs pairing ${Math.round(pairing64)} gas — ${(pairing64 / DIRECT64).toFixed(2)}x`);

// ---- the OTHER estimator, and whether the conclusion needs them to agree ----------------------------
// gateAT fits the same marginal through 3 REAL circuits. That estimator is unbiased but high-variance,
// and it lands systematically HIGHER than this synthetic instrument (~1090 vs ~1020 gas/signal, and the
// two ranges do not overlap across runs). The difference is real, not noise: all three real circuits sit
// ABOVE the synthetic line. A steeper real slope makes the pairing check MORE expensive at 490 signals,
// so using the synthetic slope is the SNARK-favourable choice and the conservative one for the finding.
// What matters is that the conclusion does not depend on which estimator is right, so both are recorded.
let bothEstimators = null;
if (existsSync(gatePath)) {
  const g = JSON.parse(readFileSync(gatePath, 'utf8'));
  const realSlope = g.onChain.perPublicSignalGas, realBase = g.onChain.plonkBaseGasAtZeroSignals;
  const realAtCeiling = realBase + realSlope * SIG;
  bothEstimators = {
    syntheticTenPoint: { marginalGasPerPublicSignal: Number(slope.toFixed(2)), seOfMarginal: Number(seSlope.toFixed(2)), residualDof: dof, pairingAtCeiling: Math.round(central), pairingAtCeilingWorstCase: Math.round(worst) },
    realThreeCircuit: { marginalGasPerPublicSignal: realSlope, seOfMarginal: g.derivedBound.seOfMarginalGasPerSignal, residualDof: 1, pairingAtCeiling: Math.round(realAtCeiling) },
    differenceGasPerSignal: Number((realSlope - slope).toFixed(2)),
    syntheticIsTheSnarkFavourableOne: realSlope > slope,
    directTotalGas: DIRECT,
    directCheaperUnderSynthetic: DIRECT < worst,
    directCheaperUnderReal: DIRECT < realAtCeiling,
    conclusionIndependentOfEstimator: DIRECT < worst && DIRECT < realAtCeiling,
  };
  console.log(`\n  two estimators of the same marginal:`);
  console.log(`    synthetic, 10 points, ${dof} dof   ${slope.toFixed(2)} +- ${seSlope.toFixed(2)} gas/signal   -> pairing ${Math.round(central)} (worst ${Math.round(worst)})`);
  console.log(`    real circuits, 3 points, 1 dof   ${realSlope.toFixed(2)} +- ${g.derivedBound.seOfMarginalGasPerSignal} gas/signal   -> pairing ${Math.round(realAtCeiling)}`);
  console.log(`    the synthetic one is ${realSlope > slope ? 'the SNARK-favourable (cheaper) estimator' : 'NOT the cheaper estimator'}; direct is ${DIRECT} gas`);
  console.log(`    direct cheaper under BOTH estimators: ${DIRECT < worst && DIRECT < realAtCeiling}`);
}

const passed = marginWorst > 0 && Math.max(...resid.map((r) => Math.abs(r.residual))) < 4 * Math.sqrt(sigma2) && dof >= 8
  && (bothEstimators === null || bothEstimators.conclusionIndependentOfEstimator);
const out = {
  at: new Date().toISOString(), passed,
  question: 'What does one public input cost a Plonk verify, measured with enough degrees of freedom to carry an extrapolation to 490 signals?',
  whyThisExists: 'gateAT estimated the marginal and its standard error from an OLS through 3 points, leaving 1 residual dof. The resulting worst-case bound moved so much between runs that the published headroom figure ranged 21.0%-46.9%. This measures the same marginal at 10 signal counts.',
  instrument: 'circuits/pubprobe<K>.circom, generated by this script: K public inputs plus one public output, a chain of quadratic constraints, all-ones witness. Public-input handling in a Plonk verifier is a generic loop over nPublic, so the marginal does not depend on what the circuit means. Generated sources and build outputs are removed afterwards; this artifact and the script are the reproduction path.',
  samplesPerPoint: SAMPLES,
  measured: pts,
  fit: {
    points: n, residualDof: dof,
    marginalGasPerPublicSignal: Number(slope.toFixed(2)),
    seOfMarginal: Number(seSlope.toFixed(2)),
    baseGasAtZeroSignals: Math.round(base),
    residualSd: Number(Math.sqrt(sigma2).toFixed(1)),
    worstAbsResidual: Number(Math.max(...resid.map((r) => Math.abs(r.residual))).toFixed(1)),
    rSquared: Number((1 - resid.reduce((a, r) => a + r.residual ** 2, 0) / pts.reduce((a, p) => a + (p.mean - my) ** 2, 0)).toFixed(6)),
    residuals: resid,
    spanSignals: [pts[0].publicSignals, pts.at(-1).publicSignals],
  },
  crossCheckAgainstRealCircuits: crossCheck,
  atN64: { n: 64, publicSignals: SIG64, directTotalGas: DIRECT64, pairingTotalGas: Math.round(pairing64), ratio: Number((pairing64 / DIRECT64).toFixed(2)) },
  bothEstimators,
  atServiceCeiling: {
    n: NC, publicSignals: SIG,
    directTotalGas: DIRECT,
    pairingCentralGas: Math.round(central),
    seOfFittedMeanAtCeiling: Number(seAtX(SIG).toFixed(2)),
    pairingWorstCaseGas: Math.round(worst),
    marginGasCentral: Math.round(marginCentral),
    marginGasWorstCase: Math.round(marginWorst),
    fractionOfCentralMarginConsumedByWorstCase: Number(fraction.toFixed(4)),
    survives: marginWorst > 0,
  },
  note: 'The 3-SE band here is the SE of the FITTED MEAN at 490 signals, which is the right uncertainty for a predicted value and correctly widens with distance from the measured range. The direct-check figure is deterministic and is taken from gateAT rather than re-measured.',
  solc: solc.version(),
};
writeFileSync(path.join(BUILD, 'probe-attest-pi-marginal.json'), JSON.stringify(out, null, 2));
console.log(`\n  artifact zk/build/probe-attest-pi-marginal.json`);

// clean up every generated file, so the repository is not left with ten throwaway circuits
for (const s of generated) rmSync(s, { force: true });
for (const K of KS) {
  const name = `pubprobe${K}`;
  for (const p of [`${name}.r1cs`, `${name}.sym`, `${name}_plonk.zkey`, `${name}_vk.json`, `Pubprobe${K}Verifier.sol`]) rmSync(path.join(BUILD, p), { force: true });
  rmSync(path.join(BUILD, `${name}_js`), { recursive: true, force: true });
}
console.log(`  cleaned up ${generated.length} generated circuits and their build outputs`);
console.log(passed ? '\nPROBE PASSED' : '\nPROBE FAILED');
process.exit(passed ? 0 : 1);
