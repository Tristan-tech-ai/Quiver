// WHAT WOULD IT COST TO PROVE lp-risk's BLOCK 2 NOW THAT THE CLOSED FORM IS KNOWN?
//
// `gateLP2-expectation-cost.mjs` measured `lpexpectation.circom` at 36,613 R1CS constraints against
// the 4,096 that `hez_final_12.ptau` admits — 8.94x over — and concluded that the ceremony file is
// what blocks proving `expectedDivergence.expectedIlPct`. That conclusion is correct ABOUT THAT
// CIRCUIT, and `docs/verify-lp-risk.md` repeats it as "what actually blocks the quadrature: the
// ceremony file".
//
// It is no longer the binding constraint, and this probe is the number that says so.
//
// `lpexpectation.circom` encodes the ENGINE'S 401-POINT QUADRATURE, strided to 81 nodes. It was
// written before E[IL](v) = exp(-v/8) - 1 was found. A circuit for the CLOSED FORM needs ONE
// exponential, not 81 nodes each carrying a division with a wide signed residual range check — and
// the per-node division is exactly what `lpexpectation.circom`'s own header names as "the binding
// cost". So the honest question is not "does the quadrature fit" but "does one exponential fit", and
// nobody had asked it.
//
// THE SCHEME MEASURED HERE. exp(-v/8) by range reduction and repeated squaring, every intermediate
// in (0, 1] so no signal ever needs a sign:
//
//     t    = v / (8 * 2^M)                 small, so a short Taylor converges
//     E_M  = exp(-t)                       DEG Taylor terms; even terms add, odd subtract, and the
//                                          whole polynomial is ONE linear combination — free
//     E_k  = E_{k+1}^2                      M squarings walk back up to exp(-v/8)
//     eHat = E_0 rescaled onto the 1e-9 grid
//
// Every step is one range-checked fixed-point rescale, which is the only primitive used. M = 8 and
// DEG = 12 are not tuned: M is the smallest power for which t stays under 0.11 across the live
// domain, and DEG is the smallest degree whose next Taylor term is under the internal 1e-18 scale.
//
// THIS PROBE DOES NOT WIRE ANYTHING, and the circuit source lives inside this file rather than in
// `zk/circuits/` on purpose. An unwired circuit sitting in the circuits directory is how this service
// ended up being described as having "circuits that serve nobody"; a cost probe should leave a
// number behind, not an artifact that looks like a commitment. The compile happens in a scratch
// directory under `zk/build/` and is removed afterwards.
//
// WHY THE NUMBER DOES NOT LICENCE WIRING IT. Measured below: the closed form and the engine's
// quadrature publish a DIFFERENT 4-decimal percent on part of the domain. Certifying the closed form
// while the engine serves the quadrature would put a proof next to a response that disagrees with it
// in the last digit it prints. `gates/gateLP-revert.mjs` revert 2 exists to catch exactly that
// substitution. So this probe measures a cost and states a blocker; it does not propose a wiring.
//
//   node zk/scripts/probe-lpclosed-cost.mjs
import { writeFileSync, mkdirSync, rmSync, readFileSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ZK = join(HERE, '..');
const BUILD = join(ZK, 'build');
const SCRATCH = join(BUILD, '.probe-lpclosed');
const CIRCOM = join(ZK, 'circom.exe');

const M = 8, DEG = 12, SPOW = 18, SPOW_OUT = 9, NB = 64, TOL = 1;

const CIRCUIT = `pragma circom 2.1.6;

include "circomlib/circuits/bitify.circom";
include "circomlib/circuits/comparators.circom";

// COST PROBE, generated by zk/scripts/probe-lpclosed-cost.mjs. Not a wired circuit.
template LpClosed(SPOW, SPOW_OUT, M, DEG, NB, TOL) {
    signal input vHat;
    signal input eHat;
    signal input t;
    signal input p[DEG + 1];
    signal input E[M + 1];

    signal output polyResidual;
    signal output outResidual;

    var SS = 1;  for (var i = 0; i < SPOW;     i++) { SS = SS * 10; }
    var SO = 1;  for (var i = 0; i < SPOW_OUT; i++) { SO = SO * 10; }
    var RATIO = SS / SO;
    var DIV = 8;  for (var i = 0; i < M; i++) { DIV = DIV * 2; }

    var A[DEG + 1];
    var fact = 1;
    A[0] = SS;
    for (var j = 1; j <= DEG; j++) { fact = fact * j; A[j] = SS \\ fact; }

    component rb[DEG + M + 3];
    component rw[DEG + M + 3];
    var nr = 0;

    signal tR;
    tR <== t * DIV - vHat * RATIO;
    rb[nr] = Num2Bits(NB);   rb[nr].in <== 2 * tR + TOL * SS;
    rw[nr] = LessEqThan(NB); rw[nr].in[0] <== 2 * tR + TOL * SS; rw[nr].in[1] <== 2 * TOL * SS; rw[nr].out === 1;
    nr = nr + 1;

    p[0] === SS;
    p[1] === t;
    signal pR[DEG + 1];
    for (var j = 1; j < DEG; j++) {
        pR[j] <== p[j] * t - p[j + 1] * SS;
        rb[nr] = Num2Bits(NB);   rb[nr].in <== 2 * pR[j] + TOL * SS;
        rw[nr] = LessEqThan(NB); rw[nr].in[0] <== 2 * pR[j] + TOL * SS; rw[nr].in[1] <== 2 * TOL * SS; rw[nr].out === 1;
        nr = nr + 1;
    }

    signal polySum;
    polySum <== A[0] * p[0] - A[1] * p[1] + A[2] * p[2] - A[3] * p[3] + A[4] * p[4] - A[5] * p[5]
              + A[6] * p[6] - A[7] * p[7] + A[8] * p[8] - A[9] * p[9] + A[10] * p[10] - A[11] * p[11]
              + A[12] * p[12];
    polyResidual <== E[M] * SS - polySum;
    rb[nr] = Num2Bits(NB);   rb[nr].in <== 2 * polyResidual + TOL * SS;
    rw[nr] = LessEqThan(NB); rw[nr].in[0] <== 2 * polyResidual + TOL * SS; rw[nr].in[1] <== 2 * TOL * SS; rw[nr].out === 1;
    nr = nr + 1;

    signal sq[M];
    signal sR[M];
    for (var k = 0; k < M; k++) {
        sq[k] <== E[k + 1] * E[k + 1];
        sR[k] <== sq[k] - E[k] * SS;
        rb[nr] = Num2Bits(NB);   rb[nr].in <== 2 * sR[k] + TOL * SS;
        rw[nr] = LessEqThan(NB); rw[nr].in[0] <== 2 * sR[k] + TOL * SS; rw[nr].in[1] <== 2 * TOL * SS; rw[nr].out === 1;
        nr = nr + 1;
    }

    outResidual <== eHat * RATIO - E[0];
    rb[nr] = Num2Bits(NB);   rb[nr].in <== 2 * outResidual + TOL * SS;
    rw[nr] = LessEqThan(NB); rw[nr].in[0] <== 2 * outResidual + TOL * SS; rw[nr].in[1] <== 2 * TOL * SS; rw[nr].out === 1;
    nr = nr + 1;
}

component main {public [vHat, eHat]} = LpClosed(${SPOW}, ${SPOW_OUT}, ${M}, ${DEG}, ${NB}, ${TOL});
`;

// ── compile and count ────────────────────────────────────────────────────────────────────────────
rmSync(SCRATCH, { recursive: true, force: true });
mkdirSync(SCRATCH, { recursive: true });
const SRC = join(SCRATCH, 'probe_lpclosed.circom');
writeFileSync(SRC, CIRCUIT);

if (!existsSync(CIRCOM)) throw new Error(`circom is not at ${CIRCOM} — it is not on PATH and this probe needs it`);

const cc = spawnSync(CIRCOM, [SRC, '--r1cs', '-l', join(ZK, 'node_modules'), '-o', SCRATCH], { encoding: 'utf8', timeout: 600_000 });
const raw = `${cc.stdout || ''}${cc.stderr || ''}`;
// eslint-disable-next-line no-control-regex
const out = raw.replace(/\[[0-9;]*m/g, '');
if (cc.status !== 0) { console.error(out); throw new Error('circom failed to compile the probe'); }

// THE REGEX TRAP. /linear constraints: (\d+)/ ALSO MATCHES "non-linear constraints: 2857". Both
// patterns are anchored to the start of the line so the two counts cannot be confused, and the total
// is cross-checked against snarkjs below rather than trusted from this parse.
const nonLinear = Number((out.match(/^non-linear constraints: (\d+)$/m) || [])[1] ?? NaN);
const linear = Number((out.match(/^linear constraints: (\d+)$/m) || [])[1] ?? NaN);
if (!Number.isFinite(nonLinear) || !Number.isFinite(linear)) {
  console.error(out);
  throw new Error('could not read both constraint counts from circom. The numbers below would be invented');
}

const R1CS = join(SCRATCH, 'probe_lpclosed.r1cs');
const sj = spawnSync(process.execPath, [join(ZK, 'node_modules', 'snarkjs', 'cli.js'), 'r1cs', 'info', R1CS], { encoding: 'utf8', timeout: 600_000 });
const sjOut = (`${sj.stdout || ''}${sj.stderr || ''}`).replace(/\[[0-9;]*m/g, ''); // eslint-disable-line no-control-regex
const snarkjsTotal = Number((sjOut.match(/# of Constraints:\s*(\d+)/) || [])[1] ?? NaN);
if (!Number.isFinite(snarkjsTotal)) { console.error(sjOut); throw new Error('could not read the constraint count from snarkjs'); }
if (snarkjsTotal !== nonLinear + linear) {
  throw new Error(`circom reports ${nonLinear} + ${linear} = ${nonLinear + linear} constraints, snarkjs reports ${snarkjsTotal}. One of the two parses is wrong and the figure must not be published until they agree`);
}

// ── does the scheme carry an HONEST witness? Exact integers, the circuit's own tolerances ─────────
const SS = 10n ** BigInt(SPOW), SO = 10n ** BigInt(SPOW_OUT), RATIO = SS / SO;
const DIV = 8n * 2n ** BigInt(M);
const A = [SS];
{ let f = 1n; for (let j = 1; j <= DEG; j++) { f *= BigInt(j); A.push(SS / f); } }
const abs = (x) => (x < 0n ? -x : x);
const LIM = BigInt(TOL) * SS;

// An INDEPENDENT reference for exp(-v/8): 40-digit BigInt Taylor with its own range reduction, so
// the scheme is not checked against itself.
const P = 10n ** 40n;
function refExp(vHat) {
  const x = (vHat * P) / (8n * SO);
  let K = 0, xr = x;
  while (xr > P / 2n) { xr /= 2n; K++; }
  let term = P, sum = P, sign = -1n;
  for (let j = 1; j <= 90; j++) { term = (term * xr) / (P * BigInt(j)); sum += sign * term; sign = -sign; if (term === 0n) break; }
  for (let k = 0; k < K; k++) sum = (sum * sum) / P;
  return sum;
}

function witness(vHat) {
  const t = (vHat * RATIO) / DIV;
  const tR = t * DIV - vHat * RATIO;
  const p = [SS, t], pR = [0n, 0n];
  for (let j = 1; j < DEG; j++) { const nx = (p[j] * t + SS / 2n) / SS; p.push(nx); pR.push(p[j] * t - nx * SS); }
  let polySum = 0n;
  for (let j = 0; j <= DEG; j++) polySum += (j % 2 === 0 ? 1n : -1n) * A[j] * p[j];
  const EM = (polySum + SS / 2n) / SS;
  const polyResidual = EM * SS - polySum;
  const E = new Array(M + 1); E[M] = EM;
  const sR = [];
  for (let k = M - 1; k >= 0; k--) { E[k] = (E[k + 1] * E[k + 1] + SS / 2n) / SS; sR[k] = E[k + 1] * E[k + 1] - E[k] * SS; }
  const eHat = (E[0] + RATIO / 2n) / RATIO;
  return { t, tR, p, pR, EM, polyResidual, E, sR, eHat, outResidual: eHat * RATIO - E[0] };
}

// The live domain: where L = exp(-v/8) is still nonzero on the 1e-9 grid. Past it the service's own
// figure has saturated at -100.0000% and there is nothing left to certify.
const V_MAX = 166;
const SAMPLES = 40000;
let violations = 0, worstStep = 0, worstStepAt = 0;
const worst = { t: 0n, powers: 0n, poly: 0n, squaring: 0n, output: 0n };
for (let i = 1; i <= SAMPLES; i++) {
  const v = (V_MAX * i) / SAMPLES;
  const vHat = BigInt(Math.round(v * 1e9));
  const w = witness(vHat);
  const take = (key, r) => { const a = 2n * abs(r); if (a > worst[key]) worst[key] = a; if (a > LIM) violations++; };
  take('t', w.tR);
  for (let j = 1; j < DEG; j++) take('powers', w.pR[j]);
  take('poly', w.polyResidual);
  for (let k = 0; k < M; k++) take('squaring', w.sR[k]);
  take('output', w.outResidual);
  const refHat = (refExp(vHat) * SO + P / 2n) / P;
  const d = Number(w.eHat - refHat);
  if (Math.abs(d) > Math.abs(worstStep)) { worstStep = d; worstStepAt = v; }
}

// ── THE BLOCKER, measured: does the closed form publish the engine's own served digit? ───────────
const ilOfRatio = (r) => (r > 0 ? (2 * Math.sqrt(r)) / (1 + r) - 1 : -1);
function engineQuadrature(v) {
  const sd = Math.sqrt(v);
  let sum = 0, w = 0;
  const N = 400, lo = -6, hi = 6;
  for (let i = 0; i <= N; i++) {
    const z = lo + ((hi - lo) * i) / N;
    const pdf = Math.exp(-0.5 * z * z);
    const r = Math.exp(-0.5 * v + sd * z);
    sum += pdf * ilOfRatio(r); w += pdf;
  }
  return sum / w;
}
const closedForm = (v) => Math.expm1(-v / 8);
const round4 = (x) => Number(Number(x).toFixed(4));   // src/engine/lpRisk.js:110, round(x*100, 4)

function substitutionCost(vs, label) {
  let mismatches = 0, worstGap = 0, worstAt = 0;
  for (const v of vs) {
    const q = engineQuadrature(v) * 100, c = closedForm(v) * 100;
    const g = Math.abs(q - c);
    if (g > worstGap) { worstGap = g; worstAt = v; }
    if (round4(q) !== round4(c)) mismatches++;
  }
  return { label, samples: vs.length, mismatches, oneIn: mismatches ? Math.round(vs.length / mismatches) : null, worstGapPercent: worstGap, worstGapAtV: worstAt };
}
const linDomain = []; for (let i = 1; i <= SAMPLES; i++) linDomain.push((V_MAX * i) / SAMPLES);
const logDomain = []; for (let i = 0; i <= 200000; i++) logDomain.push(Math.exp(Math.log(1e-8) + (Math.log(1e4) - Math.log(1e-8)) * i / 200000));
const substitution = [
  substitutionCost(linDomain, `linear, ${SAMPLES} v in (0, ${V_MAX}] — the live domain`),
  substitutionCost(logDomain, 'log-spaced, 200,001 v in [1e-8, 1e4] — the circuit\'s declared range'),
];

// ── what lpexpectation.circom costs, read from its own r1cs rather than restated ─────────────────
function r1csConstraints(file) {
  const p = join(BUILD, file);
  if (!existsSync(p)) return null;
  const r = spawnSync(process.execPath, [join(ZK, 'node_modules', 'snarkjs', 'cli.js'), 'r1cs', 'info', p], { encoding: 'utf8', timeout: 600_000 });
  const o = (`${r.stdout || ''}${r.stderr || ''}`).replace(/\[[0-9;]*m/g, ''); // eslint-disable-line no-control-regex
  const n = Number((o.match(/# of Constraints:\s*(\d+)/) || [])[1] ?? NaN);
  return Number.isFinite(n) ? n : null;
}
const lpexpectation = r1csConstraints('lpexpectation.r1cs');
const lpbracket = r1csConstraints('lpbracket.r1cs');
const PTAU_CEILING = 4096;

const artifact = {
  at: new Date().toISOString(),
  passed: violations === 0 && worstStep === 0 && snarkjsTotal < PTAU_CEILING,
  scheme: { internalScale: `1e-${SPOW}`, publishedScale: `1e-${SPOW_OUT}`, squarings: M, taylorTerms: DEG, rangeCheckBits: NB, tolerance: TOL, rangeReductionDivisor: Number(DIV) },
  constraints: { nonLinear, linear, total: nonLinear + linear, snarkjsTotal, ptauCeiling: PTAU_CEILING, fractionOfCeiling: (nonLinear + linear) / PTAU_CEILING },
  comparison: { lpexpectationR1cs: lpexpectation, lpbracketR1cs: lpbracket, lpexpectationTimesOverCeiling: lpexpectation == null ? null : lpexpectation / PTAU_CEILING },
  witness: {
    domain: `(0, ${V_MAX}]`, samples: SAMPLES,
    toleranceViolations: violations,
    worstGridStepErrorVsIndependentReference: worstStep,
    worstGridStepErrorAtV: worstStepAt,
    worstResidualFractionOfTolerance: Object.fromEntries(Object.entries(worst).map(([k, v]) => [k, Number(v) / Number(LIM)])),
  },
  substitution,
  conclusion: (nonLinear + linear) < PTAU_CEILING
    ? 'The ceremony file is NOT what blocks proving block 2. A closed-form circuit fits inside hez_final_12 with room to spare, and carries an exact witness across the live domain. What blocks it is that the engine serves a quadrature and this would certify the closed form: the two print a different 4-decimal percent on part of the domain, so wiring it would put a proof beside a response it visibly disagrees with. The fix is engine-side (serve Math.expm1(-v/8), which is exact and 802x cheaper) and src/engine/ is frozen.'
    : 'A closed-form circuit does not fit either.',
};

writeFileSync(join(BUILD, 'probe-lpclosed-cost.json'), `${JSON.stringify(artifact, null, 2)}\n`);
rmSync(SCRATCH, { recursive: true, force: true });

console.log('PROBE: what a CLOSED-FORM circuit for lp-risk block 2 would cost\n');
console.log(`  scheme                        exp(-v/8) via ${DEG} Taylor terms + ${M} squarings, internal 1e-${SPOW}`);
console.log(`  circom                        ${nonLinear} non-linear + ${linear} linear = ${nonLinear + linear}`);
console.log(`  snarkjs cross-check           ${snarkjsTotal} (agrees)`);
console.log(`  hez_final_12 ceiling          ${PTAU_CEILING} — this uses ${((nonLinear + linear) / PTAU_CEILING * 100).toFixed(1)}%`);
console.log(`  lpexpectation.circom          ${lpexpectation} R1CS = ${(lpexpectation / PTAU_CEILING).toFixed(2)}x the ceiling`);
console.log(`  lpbracket.circom (wired)      ${lpbracket} R1CS\n`);
console.log(`  witness, ${SAMPLES} v in (0, ${V_MAX}]`);
console.log(`    tolerance violations        ${violations}`);
console.log(`    worst error vs a 40-digit independent reference   ${worstStep} grid step(s)`);
for (const [k, v] of Object.entries(worst)) console.log(`    worst |2r| on ${k.padEnd(10)}     ${(Number(v) / Number(LIM) * 100).toFixed(4)}% of tolerance`);
console.log('\n  THE BLOCKER — closed form vs the engine\'s served 4-decimal percent');
for (const s of substitution) {
  console.log(`    ${s.label}`);
  console.log(`      mismatches ${s.mismatches} of ${s.samples}${s.oneIn ? ` (1 in ${s.oneIn})` : ''} · worst gap ${s.worstGapPercent.toExponential(6)}% at v=${s.worstGapAtV}`);
}
console.log(`\n  wrote build/probe-lpclosed-cost.json`);
console.log(`\n${'='.repeat(74)}`);
console.log(`PROBE ${artifact.passed ? 'COMPLETE' : 'INCONCLUSIVE'} — this measures a cost and names a blocker. It wires nothing.`);
process.exit(artifact.passed ? 0 : 1);
